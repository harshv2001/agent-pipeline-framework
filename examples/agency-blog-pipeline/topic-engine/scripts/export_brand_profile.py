#!/usr/bin/env python3
"""Regenerate the pipeline's source-data/brand-profile.md from this
engine's site-profile.md plus client-config.yaml's services and palette.

Generated, safe to re-run any time (overwrites, like fold_ledger.py's
registry.csv) -- the pipeline never edits this file itself. Re-run this
whenever site-profile.md is refreshed (a new bootstrap), so the pipeline's
own copy of the client's voice never goes stale relative to the engine's.

This is the engine's SECOND write into the pipeline (export_topics_csv.py
is the first) -- both are generated artifacts the pipeline treats as
read-only input, never hand-edited on either side.

Requires site-profile.md to use exactly the headings "## Industry" and
"## Voice and personality" (agents/topic-discovery-agent.md's contract) --
this script extracts those two sections mechanically, it does not re-judge
or summarize them.

Usage:
    python scripts/export_brand_profile.py --engine . \\
        --out ../pipeline/<slug>-blog-pipeline/source-data/brand-profile.md
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from _common import load_client_config, now_iso

def extract_section(site_profile_md: str, heading: str) -> str:
    pattern = re.compile(
        r"^## " + re.escape(heading) + r"\s*\n(.*?)(?=^## |\Z)", re.DOTALL | re.MULTILINE
    )
    m = pattern.search(site_profile_md)
    if not m:
        raise ValueError(f"site-profile.md has no '## {heading}' section -- "
                          f"check it matches agents/topic-discovery-agent.md's required headings")
    return m.group(1).strip()


def build_brand_profile_md(client: dict, services: list[dict], brand: dict,
                            industry: str, voice: str, site_profile_ref: str) -> str:
    service_rows = "\n".join(
        f"| `{s['slug']}` | {s['name']} | `{s['url']}` |" for s in services
    )
    palette_rows = "\n".join(
        f"- {label.capitalize()} `{brand[key]}`"
        for key, label in (("navy", "navy"), ("parchment", "parchment"), ("accent", "accent"))
        if key in brand
    )
    name = client.get("name", "")
    return f"""---
client: {name}
exported_from: {site_profile_ref}
exported_at: '{now_iso()}'
---

# {name} — Brand Profile (pipeline's own copy)

Generated by `topic-engine/scripts/export_brand_profile.py` from the
engine's site read plus `client-config.yaml` -- re-run that script after
any bootstrap refresh. This pipeline never edits this file itself.

## Industry

{industry}

## Voice

{voice}

## Visual palette (for hero images — see agents/content-agent.md)

{palette_rows}

No literal client logo in any hero image or inline diagram — palette and
simple geometric motifs only.

## Services (for CTA/backlink accuracy)

| service_ref | name | url |
|---|---|---|
{service_rows}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--engine", type=Path, default=Path("."))
    parser.add_argument("--out", type=Path, required=True,
                         help="Path to the pipeline's source-data/brand-profile.md")
    args = parser.parse_args()

    site_profile_path = args.engine / "site-profile" / "site-profile.md"
    if not site_profile_path.exists():
        print(f"error: {site_profile_path} not found -- run the bootstrap "
              f"(scripts/analyze_site.py, then the Topic Discovery Agent) first", file=sys.stderr)
        return 1

    site_profile_md = site_profile_path.read_text(encoding="utf-8")
    config = load_client_config(args.engine)

    industry = extract_section(site_profile_md, "Industry")
    voice = extract_section(site_profile_md, "Voice and personality")

    md = build_brand_profile_md(
        config.get("client", {}), config.get("services", []), config.get("brand", {}),
        industry, voice, "topic-engine/site-profile/site-profile.md",
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md, encoding="utf-8")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
